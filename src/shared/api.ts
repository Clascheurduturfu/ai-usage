import type { AnalyticsDTO, AppMeta, HistoryDTO, HistoryFilter, OverviewDTO, PriceCatalogEntry, ProviderDetailDTO, ProviderId, QuotaSnapshotDTO, ScanStatus, Settings, UsageFilter } from './types'
import type { UpdateChannel, UpdateStatus } from './update'
import type { AgentProfile, EndpointRecord, EndpointTest, LaunchSelection, ManagerSnapshot, McpRecord, MigrationPreview, ProxyRecord, SharingStatus, SkillFolder, SyncPreview, SyncResult, InstallPreview, McpSetupPreview, McpDeviceStatus } from './manager'

export function createApi(
  invoke: <T>(method: string, params?: unknown) => Promise<T>,
  subscribe: (event: string, cb: () => void) => () => void,
  native: { pickFolder(): Promise<string | null>; pickJsonFile(): Promise<string | null>; openPath(p: string): Promise<string>; mcpControl?(action: 'stop' | 'resume', name: string): Promise<unknown> }
) {
  return {
    meta: () => invoke<AppMeta>('app:meta'),
    getSettings: () => invoke<Settings>('settings:get'),
    setSettings: (patch: Partial<Settings>) => invoke<Settings>('settings:set', patch),
    getOverview: () => invoke<OverviewDTO>('data:overview'),
    getProvider: (id: ProviderId) => invoke<ProviderDetailDTO>('data:provider', id),
    getAnalytics: (filter?: UsageFilter) => invoke<AnalyticsDTO>('data:analytics', filter),
    getHistory: (filter: HistoryFilter) => invoke<HistoryDTO>('data:history', filter),
    getPriceCatalog: () => invoke<PriceCatalogEntry[]>('pricing:catalog'),
    openPriceSource: (url: string) => invoke<void>('pricing:source', url),
    getQuota: () => invoke<QuotaSnapshotDTO>('quota:get'),
    refreshQuota: () => invoke<QuotaSnapshotDTO>('quota:refresh'),
    fullRescan: () => invoke<ScanStatus>('scan:full'),
    reindex: () => invoke<ScanStatus>('scan:reindex'),
    pickFolder: native.pickFolder,
    pickJsonFile: native.pickJsonFile,
    openPath: native.openPath,
    onDataUpdated: (cb: () => void) => subscribe('data:updated', cb),
    onManagerUpdated: (cb: () => void) => subscribe('manager:updated', cb),
    onUpdateStatus: (cb: () => void) => subscribe('update:updated', cb),
    updateStatus: () => invoke<UpdateStatus>('update:status'),
    checkForUpdates: () => invoke<UpdateStatus>('update:check'),
    setUpdateChannel: (channel: UpdateChannel) => invoke<UpdateStatus>('update:channel', channel),
    setUpdateAutoCheck: (enabled: boolean) => invoke<UpdateStatus>('update:autoCheck', enabled),
    downloadUpdate: () => invoke<UpdateStatus>('update:download'),
    installUpdate: () => invoke<UpdateStatus>('update:install'),
    openReleases: () => invoke<void>('update:releases'),
    getManager: () => invoke<ManagerSnapshot>('manager:get'),
    stopMcp: (name: string) => native.mcpControl ? native.mcpControl('stop', name) : invoke<void>('mcp:pause', name),
    resumeMcp: (name: string) => native.mcpControl ? native.mcpControl('resume', name) : invoke<void>('mcp:resume', name),
    saveEndpoint: (endpoint: EndpointRecord, secret?: string) => invoke<void>('endpoint:save', { endpoint, secret }),
    deleteEndpoint: (id: string) => invoke<void>('endpoint:delete', id),
    testEndpoint: (id: string) => invoke<EndpointTest>('endpoint:test', id),
    testChat: (id: string, model: string, prompt: string) => invoke<{ text: string; latencyMs: number }>('endpoint:chat', { id, model, prompt }),
    saveProxy: (proxy: ProxyRecord, clientSecret?: string) => invoke<void>('proxy:save', { proxy, clientSecret }),
    deleteProxy: (id: string) => invoke<void>('proxy:delete', id),
    startProxy: (id: string) => invoke<void>('proxy:start', id),
    stopProxy: (id: string) => invoke<void>('proxy:stop', id),
    saveProfile: (profile: AgentProfile, activate: boolean) => invoke<void>('profile:save', { profile, activate }),
    deleteProfile: (id: string) => invoke<void>('profile:delete', id),
    setAutoSync: (enabled: boolean) => invoke<void>('manager:autoSync', enabled),
    setSyncNotifications: (enabled: boolean) => invoke<void>('manager:notifications', enabled),
    activateProfile: (id: string) => invoke<SyncResult>('profile:activate', id),
    useStandardProfile: (agentId: string) => invoke<SyncResult>('profile:standard', agentId),
    previewInstall: (kind: 'skill' | 'mcp', source: string, selected?: string) => invoke<InstallPreview>('install:preview', { kind, source, selected }),
    confirmInstall: (id: string) => invoke<{ name: string }>('install:confirm', id),
    setMcpAuth: (name: string, enabled: boolean) => invoke<SyncResult>('mcp:auth', { name, enabled }),
    loginMcp: (name: string) => invoke<void>('mcp:login', name),
    logoutMcp: (name: string) => invoke<void>('mcp:logout', name),
    previewMcpSetup: (names?: string[]) => invoke<McpSetupPreview>('mcp:preparePreview', names),
    prepareMcp: (id: string) => invoke<{ prepared: string[]; failed: Record<string, string> }>('mcp:prepare', id),
    checkMcp: (name: string) => invoke<McpDeviceStatus>('mcp:check', name),
    setAwsMcpProfile: (name: string, profile: string) => invoke<void>('mcp:awsProfile', { name, profile }),
    setLocalMcpLaunch: (name: string, launch: { command: string; args: string[]; env?: Record<string, string> } | null) => invoke<void>('mcp:localLaunch', { name, launch }),
    getLocalMcpLaunch: (name: string) => invoke<{ command: string; args: string[]; env: Record<string, string> }>('mcp:localLaunchGet', name),
    configureWorkspaceClient: (client: unknown) => invoke<{ saved: boolean }>('workspace:configureClient', client),
    importWorkspaceClientFile: (file: string) => invoke<void>('workspace:clientFile', file),
    signInWorkspace: (account: string) => invoke<void>('workspace:signIn', account),
    signOutWorkspace: (account: string) => invoke<void>('workspace:signOut', account),
    enableWorkspace: () => invoke<{ enabled: boolean }>('workspace:enable'),
    openMcpHelp: (name: string) => invoke<void>('mcp:help', name),
    previewSync: () => invoke<SyncPreview>('manager:preview'),
    applySync: (id: string) => invoke<SyncResult>('manager:apply', id),
    adoptSyncEdits: (id: string) => invoke<SyncPreview>('manager:adopt', id),
    syncAgents: () => invoke<SyncResult>('manager:sync'),
    refreshAntigravity: () => invoke<void>('agent:refreshAntigravity'),
    restoreSync: (backupId: string) => invoke<SyncResult>('manager:restore', backupId),
    saveMcp: (server: McpRecord, oldName?: string) => invoke<{ warnings: string[]; sync?: SyncResult }>('mcp:save', { server, oldName }),
    deleteMcp: (name: string) => invoke<void>('mcp:delete', name),
    setMcpEnabled: (name: string, enabled: boolean) => invoke<SyncResult>('mcp:setEnabled', { name, enabled }),
    setMcpCompact: (name: string, enabled: boolean) => invoke<SyncResult>('mcp:setCompact', { name, enabled }),
    setSkillEnabled: (name: string, enabled: boolean) => invoke<SyncResult>('skill:setEnabled', { name, enabled }),
    setSkillsEnabled: (names: string[], enabled: boolean) => invoke<SyncResult>('skill:setManyEnabled', { names, enabled }),
    saveSkillFolders: (folders: SkillFolder[]) => invoke<void>('skillFolders:save', folders),
    setContextBudget: (tokens: number) => invoke<void>('manager:contextBudget', tokens),
    resetMcpCalls: (name?: string) => invoke<void>('mcp:resetCalls', name),
    saveInstructions: (text: string) => invoke<void>('instructions:save', text),
    readSkill: (name: string) => invoke<string>('skill:read', name),
    saveSkill: (name: string, text: string) => invoke<void>('skill:save', { name, text }),
    deleteSkill: (name: string) => invoke<void>('skill:delete', name),
    migrationPreview: () => invoke<MigrationPreview>('migration:preview'),
    importLegacy: () => invoke<MigrationPreview>('migration:import'),
    configureSharing: (folder: string, passphrase: string) => invoke<SharingStatus>('sharing:configure', { folder, passphrase }),
    unlockSharing: (passphrase: string) => invoke<SharingStatus>('sharing:unlock', passphrase),
    sharingSettings: () => invoke<{ folder: string; passphrase: string }>('sharing:settings'),
    sharingFileExists: (folder: string) => invoke<boolean>('sharing:exists', { folder }),
    publishSharing: (settings?: { folder: string; passphrase: string }) => invoke<SharingStatus>('sharing:publish', settings),
    importSharing: (settings: boolean | { folder: string; passphrase: string } = false) => invoke<SharingStatus>('sharing:import', typeof settings === 'boolean' ? { resolveConflict: settings } : settings),
    launchAgent: (selection: LaunchSelection) => invoke<{ pid: number }>('agent:launch', selection),
    applyEndpointDefault: (profileId: string) => invoke<SyncResult>('agent:default', profileId),
    restoreEndpointDefault: (agentId: string) => invoke<SyncResult>('agent:restore', agentId)
  }
}
export type AiuApi = ReturnType<typeof createApi>
